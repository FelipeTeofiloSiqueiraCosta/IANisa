# Chat da área Arquivos contra a prévia local (agentes de mentira), fora do npm test:
#   PORTA=6811 node test/previa/servidor.mjs &  e  python3 test/chat-acp.browser.py   (prévia zerada a cada rodada)
import re, sys, time
from playwright.sync_api import sync_playwright
BASE = "http://localhost:6811"
OUT = "/tmp/"
erros = []
def ok(cond, msg):
    print(("OK   " if cond else "FALHA"), msg)
    if not cond: erros.append(msg)
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 1400, "height": 900}, bypass_csp=True)  # o CSP do portal barra o wait_for_function
    # guarda os WebSockets pra derrubar a conexão de propósito (o túnel faz isso com conexão parada)
    pg.add_init_script("const W=window.WebSocket;window.__socks=[];window.WebSocket=class extends W{constructor(...a){super(...a);window.__socks.push(this);}};")
    logs = []
    pg.on("console", lambda m: logs.append(m.type + ": " + m.text) if m.type in ("error", "warning") else None)
    pg.on("pageerror", lambda e: logs.append("pageerror: " + str(e)))
    pg.goto(BASE + "/portal/#arquivos"); pg.wait_for_timeout(1200)
    # botão "Nova conversa" de algum painel da grade
    pg.locator("button[aria-label='Nova conversa']").first.click(); pg.wait_for_timeout(800)
    novo = pg.locator("#composer-novo textarea")
    ok(novo.is_visible(), "compositor de conversa nova aparece")
    modelos = pg.locator("#composer-novo select[aria-label='Modelo'] option").all_text_contents()
    ok("Opus 5.5" in modelos and "GPT-6 Astra" in modelos, "pílula de modelo tem os dois agentes: %s" % modelos)
    esforco = pg.locator("#composer-novo select[aria-label='Esforço']").input_value()
    ok(esforco == "medium", "esforço padrão vem do agente (%s)" % esforco)
    novo.fill("olá, lista a pasta"); novo.press("Enter")
    pg.wait_for_selector(".conv .msg.assistant", timeout=8000); pg.wait_for_timeout(1500)
    conv = pg.locator(".conv:not([hidden])")
    ok(conv.locator(".msg.user").first.inner_text().strip() == "olá, lista a pasta", "mensagem da pessoa aparece uma vez")
    ok(conv.locator(".msg.user").count() == 1, "sem eco duplicado (%d)" % conv.locator(".msg.user").count())
    ok(conv.locator(".chat-vazio").count() == 0, "sem o aviso de conversa vazia depois de começar")
    txt = conv.locator(".msg.assistant").last.inner_text()
    ok("Prévia local: recebi" in txt and "um item" in txt, "resposta em pedaços vira um markdown só")
    ok(conv.locator(".msg.tool .tool-nome").first.inner_text() == "Bash", "ferramenta com nome Bash")
    ok("Plano:" in conv.locator(".msg.nota").first.inner_text(), "plano aparece")
    ok(conv.locator(".msg.pensando").count() == 1, "raciocínio aparece")
    ok(not conv.locator(".anel").is_hidden(), "anel de contexto aparece")
    abas = pg.locator(".aba, [role=tab]").all_text_contents()
    ok(any("olá, lista a pasta" in a for a in abas), "aba com o título da conversa: %s" % [a.strip()[:30] for a in abas])
    # permissão
    area = conv.locator("textarea")
    area.fill("pode apagar? permissão"); area.press("Enter")
    pg.wait_for_selector(".conv:not([hidden]) .perm-card", timeout=5000)
    botoes = conv.locator(".perm-card button").all_text_contents()
    ok(botoes == ["Sim", "Sim, sempre", "Não"], "cartão de permissão com as opções do agente: %s" % botoes)
    pg.screenshot(path=OUT + "chat-acp-permissao.png")
    conv.locator(".perm-card button", has_text="Sim, sempre").click()
    pg.wait_for_function("document.querySelectorAll('.conv:not([hidden]) .msg.assistant').length>=2", timeout=8000); pg.wait_for_timeout(800)
    ok(conv.locator(".perm-card").count() == 0, "cartão some depois de responder")
    # parar
    area.fill("demorar um pouco"); area.press("Enter"); pg.wait_for_timeout(1500)
    ok("parar" in (conv.locator("button.enviar").get_attribute("class") or ""), "botão vira parar enquanto roda")
    conv.locator("button.enviar").click(); pg.wait_for_timeout(1500)
    ok("Interrompido." in conv.inner_text(), "parar interrompe")
    # trocar modelo na conversa aberta
    conv.locator("select[aria-label='Modelo']").select_option("sonnet"); pg.wait_for_timeout(400)
    ok(conv.locator("select[aria-label='Modelo']").input_value() == "sonnet", "troca de modelo vale na conversa")
    pg.screenshot(path=OUT + "chat-acp-conversa.png")
    # duas perguntas: uma por vez; o que já foi digitado sobrevive à queda da conexão
    msgs = conv.locator(".conv-msgs")
    area.fill("duas perguntas"); area.press("Enter")
    pg.wait_for_selector(".conv:not([hidden]) .perm-card.pergunta", timeout=5000)
    card = conv.locator(".perm-card.pergunta")
    ok(card.locator(".pq-passo").inner_text() == "1 de 2", "contador 1 de 2")
    ok(card.locator("fieldset.pq:visible").count() == 1, "só uma pergunta à vista")
    ok(card.locator("button", has_text="Anterior").is_hidden(), "sem Anterior na primeira")
    card.locator("fieldset.pq:visible .pq-livre").fill("um carrossel curto")
    card.locator("fieldset.pq:visible .pq-livre").press("Enter")
    ok(card.locator(".pq-passo").inner_text() == "2 de 2" and card.locator("button.primary").inner_text() == "Responder", "Enter avança pra segunda, botão vira Responder")
    card.locator("button", has_text="Anterior").click()
    ok(msgs.evaluate("m=>m.scrollHeight>m.clientHeight+50"), "conversa tem o que rolar")
    pg.screenshot(path=OUT + "chat-acp-perguntas.png")
    msgs.evaluate("m=>m.scrollTop=0")
    pg.evaluate("window.__socks.forEach(s=>s.close())"); pg.wait_for_timeout(2500)
    card = conv.locator(".perm-card.pergunta")
    ok(card.locator("fieldset.pq:visible .pq-livre").input_value() == "um carrossel curto", "texto digitado sobrevive à reconexão")
    ok(msgs.evaluate("m=>m.scrollTop") == 0, "reconexão não rola a conversa pro fim")
    card.locator("label.pq-op", has_text="Reels").click(); pg.wait_for_timeout(500)
    ok(card.locator(".pq-passo").inner_text() == "2 de 2", "marcar escolha única avança sozinho")
    card.locator("label.pq-op", has_text="Leve").click(); pg.wait_for_timeout(500)
    ok(card.locator(".pq-passo").inner_text() == "2 de 2", "na última não manda sozinho")
    card.locator("button.primary", has_text="Responder").click()
    pg.wait_for_function("document.querySelector('.conv:not([hidden])').innerText.includes('Tua resposta')", timeout=8000)
    nota = conv.locator(".msg.nota", has_text="Tua resposta").last.inner_text()
    ok("um carrossel curto" in nota and "Reels" in nota and "Leve" in nota, "manda as duas respostas: %s" % nota)
    pg.wait_for_function("document.querySelectorAll('.conv:not([hidden]) .msg.user').length>=4", timeout=8000); pg.wait_for_timeout(2500)
    # recarregar: a aba da conversa volta com o histórico
    pg.reload(); pg.wait_for_timeout(2500)
    conv2 = pg.locator(".conv:not([hidden])")
    ok(conv2.count() >= 1 and conv2.first.locator(".msg.user").count() == 4, "recarregar: conversa volta com as 4 mensagens (%d)" % (conv2.first.locator(".msg.user").count() if conv2.count() else -1))
    # recentes
    pg.locator("button[aria-label='Conversas recentes']").first.click(); pg.wait_for_timeout(600)
    ok(pg.locator("#chat-recentes .recente").count() == 1, "recentes lista a conversa")
    pg.keyboard.press("Escape")
    # Início
    pg.goto(BASE + "/portal/#inicio"); pg.wait_for_timeout(2000)
    ok(pg.locator("#home-recentes-lista li").count() >= 1, "Início lista as últimas conversas")
    ok(pg.locator("#home-prompt").is_visible(), "Início mostra o prompt de conversa nova")
    pg.screenshot(path=OUT + "chat-acp-inicio.png")
    print("\n".join(l for l in logs if "favicon" not in l)[:3000])
    b.close()
sys.exit(1 if erros else 0)
